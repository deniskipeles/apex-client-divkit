/**
 * Executes the fixtures generated by `apps/dev-server/scripts/build-tool-cases.mjs`.
 *
 * The TypeScript modules are the source of truth for the demo card, the docs and
 * these cases, so a capability that drifts from its contract — or a card button
 * with no case behind it — fails here instead of on a device.
 *
 * Record mode (`-Dtoolcase.record=true`) prints the observed result of every step
 * and writes `build/toolcase-record.json`; it exists to author new expectations,
 * never to make a red case green.
 */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [36])
class ToolConformanceTest {
    private val json = Json { ignoreUnknownKeys = true; isLenient = true }
    private val filter = System.getProperty("toolcase.filter") ?: System.getenv("TOOLCASE_FILTER")
    private val recording = System.getProperty("toolcase.record") == "true" || System.getenv("TOOLCASE_RECORD") == "true"

    private data class ToolFixture(
        val toolId: String,
        val slug: String,
        val operations: List<String>,
        val outputMapping: Map<String, String>,
        val cardActions: List<Pair<String, Map<String, String>>>,
        val notCovered: List<String>,
        val cases: List<JsonObject>
    )

    private fun load(slug: String): ToolFixture {
        val text = javaClass.getResourceAsStream("/toolcases/$slug.json")
            ?.bufferedReader()?.readText()
            ?: error("missing fixture /toolcases/$slug.json — run `pnpm tool-cases:build`")
        val root = json.parseToJsonElement(text).jsonObject
        val cardActions = root["cardActions"]?.jsonArray?.map { element ->
            val action = element.jsonObject
            action.getValue("url").jsonPrimitive.content to optionStrings(action["options"])
        } ?: emptyList()
        return ToolFixture(
            toolId = root.getValue("toolId").jsonPrimitive.content,
            slug = root.getValue("slug").jsonPrimitive.content,
            operations = root.getValue("operations").jsonArray.map { it.jsonPrimitive.content },
            outputMapping = root.getValue("outputMapping").jsonObject.mapValues { it.value.jsonPrimitive.content },
            cardActions = cardActions,
            notCovered = root["notCovered"]?.jsonArray?.map { it.jsonPrimitive.content } ?: emptyList(),
            cases = root.getValue("cases").jsonArray.map { it.jsonObject }
        )
    }

    private fun optionStrings(element: JsonElement?): Map<String, String> {
        val obj = element as? JsonObject ?: return emptyMap()
        return obj.mapValues { (_, value) -> primitiveText(value) }
    }

    private fun primitiveText(value: JsonElement): String = when (value) {
        is JsonPrimitive -> value.contentOrNull ?: value.toString()
        else -> value.toString()
    }

    private fun fixtures(): List<String> {
        val index = javaClass.getResourceAsStream("/toolcases/index.json")
            ?.bufferedReader()?.readText()
            ?: error("missing /toolcases/index.json — run `pnpm tool-cases:build`")
        return json.parseToJsonElement(index).jsonObject.getValue("tools").jsonArray
            .map { it.jsonObject.getValue("slug").jsonPrimitive.content }
            .filter { filter == null || it == filter }
    }

    private fun fixture(slug: String) = load(slug)

    @After
    fun clearSinks() {
        BiometricsTool.sink = null
        NativeToolsSuite.imageSourceSink = null
        NativeToolsSuite.liveScanSink = null
        engine.tools.impl.RealtimeWsTool.resetForTest()
    }

    // ---------------------------------------------------------------------
    // Contract mirrors
    // ---------------------------------------------------------------------

    @Test
    fun toolConformance_mirrorsTheKotlinRegistry() {
        val registry = NativeToolsSuite.registeredSchemas.associateBy { it.toolId }
        val problems = mutableListOf<String>()
        for (slug in fixtures()) {
            val fixture = fixture(slug)
            val schema = registry[fixture.toolId]
            if (schema == null) {
                problems += "${fixture.slug}: toolId ${fixture.toolId} is not in NativeToolsSuite.registeredSchemas"
                continue
            }
            if (schema.supportedOperations != fixture.operations) {
                problems += "${fixture.slug}: operations differ\n  kotlin=${schema.supportedOperations}\n  fixture=${fixture.operations}"
            }
            if (schema.defaultOutputMapping != fixture.outputMapping) {
                problems += "${fixture.slug}: output mapping differs\n  kotlin=${schema.defaultOutputMapping}\n  fixture=${fixture.outputMapping}"
            }
        }
        val fixtureIds = fixtures().map { fixture(it).toolId }.toSet()
        val missing = registry.keys - fixtureIds
        if (missing.isNotEmpty()) problems += "no conformance module for: ${missing.joinToString()}"
        assertTrue(problems.joinToString("\n"), problems.isEmpty())
    }

    @Test
    fun toolConformance_coversEveryOperation() {
        val problems = mutableListOf<String>()
        for (slug in fixtures()) {
            val fixture = fixture(slug)
            val covered = fixture.cases.flatMap { steps(it) }
                .mapNotNull { operationOf(it["url"]?.jsonPrimitive?.contentOrNull ?: return@mapNotNull null) }
                .toSet()
            val gaps = fixture.operations.filterNot { covered.contains(it) }
            if (gaps.isNotEmpty()) {
                val reasons = fixture.notCovered.filter { reason -> gaps.any { reason.startsWith("$it:") } }
                problems += "${fixture.slug}: no case for ${gaps.joinToString()} (${reasons.joinToString("; ")})"
            }
            if (fixture.cases.isEmpty()) problems += "${fixture.slug}: has no cases"
        }
        assertTrue(problems.joinToString("\n"), problems.isEmpty())
    }

    @Test
    fun toolConformance_cardActionsAreCovered() {
        val problems = mutableListOf<String>()
        for (slug in fixtures()) {
            val fixture = fixture(slug)
            val covered = fixture.cases.flatMap { steps(it) }.map { step ->
                stepKey(
                    step["url"]?.jsonPrimitive?.contentOrNull.orEmpty(),
                    optionStrings(step["payload"]?.jsonObject?.get("options"))
                )
            }.toSet()
            for ((url, options) in fixture.cardActions) {
                val key = stepKey(url, options)
                if (!covered.contains(key)) problems += "${fixture.slug}: card button $key has no case"
            }
        }
        assertTrue(problems.joinToString("\n"), problems.isEmpty())
    }

    // ---------------------------------------------------------------------
    // Execution
    // ---------------------------------------------------------------------

    @Test
    fun toolConformance_everyCaseHolds() {
        val failures = mutableListOf<String>()
        val records = mutableListOf<String>()
        for (slug in fixtures()) {
            val fixture = fixture(slug)
            for (case in fixture.cases) {
                val name = case.getValue("name").jsonPrimitive.content
                val host = case["host"]?.jsonPrimitive?.contentOrNull
                installHost(host)
                val repeat = case["stress"]?.jsonObject?.get("repeat")?.jsonPrimitive?.intOrNull ?: 1
                val distinct = case["stress"]?.jsonObject?.get("distinct")?.jsonArray?.map { it.jsonPrimitive.content } ?: emptyList()
                val observed = mutableListOf<JsonObject>()
                repeat(repeat) { iteration ->
                    try {
                        val results = mutableListOf<JsonObject>()
                        val steps = steps(case)
                        for ((index, step) in steps.withIndex()) {
                            val payload = bindPayload(step["payload"] as? JsonObject, results) ?: JsonObject(emptyMap())
                            val url = step.getValue("url").jsonPrimitive.content
                            val outcome = runBlocking { NativeToolsSuite.execute(url, payload, "conformance") }
                            val record = recordOf(outcome)
                            results += record
                            if (recording) records += "{\"tool\":\"${fixture.slug}\",\"case\":\"$name\",\"iteration\":$iteration,\"step\":$index,\"result\":${record}}"
                            val expect = step["expect"] as? JsonObject
                            if (expect != null) {
                                val problem = check(expect, outcome, record)
                                if (problem != null) failures += "${fixture.slug}/$name step $index: $problem\n   observed=$record"
                            }
                        }
                        observed += results.last()
                        val caseExpect = case["expect"] as? JsonObject
                        if (caseExpect != null && results.isNotEmpty()) {
                            val problem = check(caseExpect, null, results.last())
                            if (problem != null) failures += "${fixture.slug}/$name: $problem\n   observed=${results.last()}"
                        }
                    } catch (error: Throwable) {
                        failures += "${fixture.slug}/$name iteration $iteration threw ${error::class.simpleName}: ${error.message}"
                    }
                }
                for (field in distinct) {
                    val values = observed.mapNotNull { record ->
                        (record["data"] as? JsonObject)?.get(field)?.let { primitiveText(it) } ?: record[field]?.let { primitiveText(it) }
                    }
                    if (values.size != observed.size) failures += "${fixture.slug}/$name: stress.distinct field $field missing from a result"
                    if (values.toSet().size != values.size) failures += "${fixture.slug}/$name: stress.distinct field $field did not change: $values"
                }
            }
        }
        if (recording) {
            val out = File("build/toolcase-record.json")
            out.parentFile?.mkdirs()
            out.writeText(records.joinToString("\n", postfix = "\n"))
            records.forEach { println("RECORD $it") }
        }
        assertTrue(failures.joinToString("\n\n"), failures.isEmpty())
    }

    // ---------------------------------------------------------------------
    // Helpers
    // ---------------------------------------------------------------------

    private fun recordOf(outcome: NativeToolsSuite.ToolExecutionOutcome): JsonObject = buildMap {
        put("success", JsonPrimitive(outcome.success))
        put("status", JsonPrimitive((outcome.resultData as? JsonObject)?.get("status")?.let { primitiveText(it) } ?: ""))
        put("data", outcome.resultData)
        put("outputs", JsonObject(outcome.outputVariables.mapValues { (_, value) -> variableJson(value) }))
    }.let { JsonObject(it) }

    private fun variableJson(value: DivVariableValue): JsonElement = when (value) {
        is DivVariableValue.Str -> JsonPrimitive(value.value)
        is DivVariableValue.Bool -> JsonPrimitive(value.value)
        is DivVariableValue.IntVal -> JsonPrimitive(value.value)
        is DivVariableValue.DoubleVal -> JsonPrimitive(value.value)
        is DivVariableValue.ArrayVal -> JsonArray(value.values.map { variableJson(it) })
    }

    private fun steps(case: JsonObject): List<JsonObject> =
        case.getValue("steps").jsonArray.map { it.jsonObject }

    private fun operationOf(url: String): String? {
        val path = url.removePrefix("tools://").removePrefix("tool://")
        return path.substringAfter('/', "").ifEmpty { null }
    }

    private fun stepKey(url: String, options: Map<String, String>): String {
        val capability = url.removePrefix("tools://").substringBefore('/')
        val operation = operationOf(url).orEmpty()
        val optionPart = options.toSortedMap().entries.joinToString("&") { "${it.key}=${it.value}" }
        return "$capability/$operation?$optionPart"
    }

    /** `$prev.field` (previous step) and `$prev[n].field` bind earlier results. */
    private fun bindPayload(payload: JsonObject?, results: List<JsonObject>): JsonObject? {
        if (payload == null) return null
        return bind(payload, results) as? JsonObject
    }

    private fun bind(element: JsonElement, results: List<JsonObject>): JsonElement = when (element) {
        is JsonObject -> JsonObject(element.mapValues { (_, value) -> bind(value, results) })
        is JsonArray -> JsonArray(element.map { bind(it, results) })
        is JsonPrimitive -> {
            val text = element.contentOrNull
            if (text != null && text.startsWith("\$prev")) JsonPrimitive(resolveReference(text, results)) else element
        }
        else -> element
    }

    private fun resolveReference(reference: String, results: List<JsonObject>): String {
        val match = Regex("^\\\$prev(?:\\[(\\d+)])?\\.(.+)$").find(reference)
            ?: return reference
        val index = match.groupValues[1].ifEmpty { (results.size - 1).toString() }.toInt()
        val path = match.groupValues[2]
        val record = results.getOrNull(index) ?: return ""
        // Results carry the tool payload under `data`; allow both `$prev.field` and
        // `$prev.data.field` so a case can address either shape.
        var node: JsonElement? = listOf("data", "outputs", "").firstNotNullOfOrNull { scope ->
            val root = if (scope.isEmpty()) record else record[scope] as? JsonObject ?: return@firstNotNullOfOrNull null
            path.split('.').fold(root as JsonElement?) { cursor, segment -> (cursor as? JsonObject)?.get(segment) }
        }
        return node?.let { value ->
            when (value) {
                is JsonPrimitive -> value.contentOrNull ?: value.toString()
                else -> value.toString()
            }
        } ?: ""
    }

    /** Installs the sink set a case asks for; `none` leaves everything null. */
    private fun installHost(host: String?) {
        BiometricsTool.sink = null
        NativeToolsSuite.imageSourceSink = null
        NativeToolsSuite.liveScanSink = null
        engine.tools.impl.RealtimeWsTool.resetForTest()
        when (host) {
            "fake" -> {
                BiometricsTool.sink = { BiometricsTool.Verified(authenticated = true, method = "credential") }
                engine.tools.impl.RealtimeWsTool.transport = { _, url -> url.startsWith("ws") }
            }
            "denied" -> BiometricsTool.sink = { BiometricsTool.Verified(authenticated = false, method = "denied") }
            else -> Unit
        }
    }

    private fun check(expect: JsonObject, outcome: NativeToolsSuite.ToolExecutionOutcome?, record: JsonObject): String? {
        if (outcome != null) {
            expect["success"]?.jsonPrimitive?.booleanOrNull?.let { wanted ->
                if (outcome.success != wanted) return "expected success=$wanted but was ${outcome.success} (${record["status"]})"
            }
        }
        val status = record["status"]?.let { primitiveText(it) }
        val wantedStatus = when (val raw = expect["status"]) {
            null, JsonNull -> null
            is JsonArray -> raw.map { it.jsonPrimitive.content }
            else -> listOf(raw.jsonPrimitive.content)
        }
        if (wantedStatus != null && status !in wantedStatus) return "expected status in $wantedStatus but was $status"
        expect["errorContains"]?.jsonPrimitive?.contentOrNull?.let { needle ->
            val haystack = record.toString()
            if (!haystack.contains(needle, ignoreCase = true)) return "expected an error containing '$needle' but got $haystack"
        }
        val data = record["data"] as? JsonObject ?: JsonObject(emptyMap())
        for ((field, matcher) in (expect["data"] as? JsonObject ?: JsonObject(emptyMap()))) {
            val problem = match(field, data[field], matcher.jsonObject)
            if (problem != null) return problem
        }
        val outputs = record["outputs"] as? JsonObject ?: JsonObject(emptyMap())
        for ((field, matcher) in (expect["outputs"] as? JsonObject ?: JsonObject(emptyMap()))) {
            val problem = match(field, outputs[field], matcher.jsonObject)
            if (problem != null) return problem
        }
        for (element in (expect["notOutputs"] as? JsonArray ?: JsonArray(emptyList()))) {
            val key = element.jsonPrimitive.content
            if (outputs.containsKey(key)) return "output $key must not be mapped on this path (got ${outputs[key]})"
        }
        return null
    }

    private fun match(field: String, actual: JsonElement?, matcher: JsonObject): String? {
        val (key, expected) = matcher.entries.firstOrNull() ?: return "$field: empty matcher"
        if (actual == null || actual is JsonNull) return "$field: missing (expected $key=${expected})"
        return when (key) {
            "equals" -> {
                val wanted = primitiveText(expected)
                val got = primitiveText(actual)
                if (wanted != got) "$field: expected $wanted but was $got" else null
            }
            "type" -> {
                val wanted = expected.jsonPrimitive.content
                val ok = when (wanted) {
                    "string" -> actual is JsonPrimitive && actual.isString
                    "number" -> actual is JsonPrimitive && !actual.isString && actual.doubleOrNull != null
                    "boolean" -> actual is JsonPrimitive && actual.booleanOrNull != null
                    "array" -> actual is JsonArray
                    "object" -> actual is JsonObject
                    else -> false
                }
                if (ok) null else "$field: expected type $wanted but was $actual"
            }
            "regex" -> {
                val pattern = Regex(expected.jsonPrimitive.content)
                if (pattern.containsMatchIn(primitiveText(actual))) null
                else "$field: ${primitiveText(actual)} does not match ${pattern.pattern}"
            }
            "nonEmpty" -> {
                val empty = when (actual) {
                    is JsonArray -> actual.isEmpty()
                    is JsonObject -> actual.isEmpty()
                    else -> primitiveText(actual).isEmpty()
                }
                if (!empty) null else "$field: expected a non-empty value"
            }
            "oneOf" -> {
                val allowed = expected.jsonArray.map { primitiveText(it) }
                if (primitiveText(actual) in allowed) null else "$field: ${primitiveText(actual)} not in $allowed"
            }
            "range" -> {
                val value = (actual as? JsonPrimitive)?.doubleOrNull ?: return "$field: not a number ($actual)"
                val min = expected.jsonObject["min"]?.jsonPrimitive?.doubleOrNull
                val max = expected.jsonObject["max"]?.jsonPrimitive?.doubleOrNull
                if (min != null && value < min) "$field: $value below $min" else if (max != null && value > max) "$field: $value above $max" else null
            }
            "contains" -> {
                val needle = expected.jsonPrimitive.content
                if (primitiveText(actual).contains(needle)) null else "$field: ${primitiveText(actual)} lacks '$needle'"
            }
            "startsWith" -> {
                val prefix = expected.jsonPrimitive.content
                if (primitiveText(actual).startsWith(prefix)) null else "$field: ${primitiveText(actual)} lacks prefix '$prefix'"
            }
            else -> "$field: unknown matcher $key"
        }
    }

    private fun repeat(times: Int, block: (Int) -> Unit) {
        for (index in 0 until times) block(index)
    }
}
